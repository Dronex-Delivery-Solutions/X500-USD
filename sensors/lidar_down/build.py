#!/usr/bin/env python3
"""Build the downward single-beam rangefinder accessory (Lightware LW20)
for the X500, from PX4/PX4-gazebo-models' x500_lidar_down variant
(models/x500_lidar_down, models/LW20 - BSD-3-Clause).

This is an ADDITIVE layer: sensors/lidar_down/lidar_down.usda references
../../x500/x500.usda and adds one more rigid body + fixed joint. It does
not duplicate or modify the base vehicle.

Needs only:  pip install usd-core pycollada numpy  (no Isaac Sim to build)

    python sensors/lidar_down/build.py

PX4 side: this is a single straight-down beam, exactly what PX4 consumes
as a MAVLink DISTANCE_SENSOR message for terrain-relative altitude and
precision landing (SENS_EN_* / EKF2_RNG_* params). Isaac Sim does not ship
a ready-made bridge for this message (see sensors/README.md) - Pegasus's
PX4 backend sends IMU/baro/mag/GPS only. examples/distance_sensor_backend.py
is a first attempt at closing that gap, marked as untested.

The lidar prim uses OmniSensorGenericLidarCoreAPI (Isaac Sim 6's custom-
scan-pattern lidar authoring path) with a single beam. This schema is not
part of open-source USD, so it can only be confirmed by loading the file
in Isaac Sim - see the caveat in _usd_common.add_generic_lidar.
"""
from __future__ import annotations

import math
import sys
import urllib.request
from pathlib import Path

import numpy as np
from pxr import Gf, Usd, UsdGeom

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent / "scripts"))
from _usd_common import (  # noqa: E402
    add_collider,
    add_fixed_joint,
    add_generic_lidar,
    add_mass,
    collada_prototype,
    matrix_to_quat,
    rpy_matrix,
    rpy_quat,
    set_pose,
)

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
RAW = "https://raw.githubusercontent.com/PX4/PX4-gazebo-models/main/models/LW20/meshes/LW20.dae"

# ---- numbers from PX4-gazebo-models/models/x500_lidar_down/model.sdf and
#      models/LW20/model.sdf ----
MESH_POSE = ((0.0, 0.0, -0.079), (0.0, 1.57, 0.0))  # lw20_link, relative to base_link
SENSOR_LINK_POSE = ((0.0, 0.0, -0.05), (0.0, 1.57, 0.0))  # lidar_sensor_link, relative to base_link
SENSOR_LOCAL_RPY = (math.pi, 0.0, 0.0)  # the sensor's own pose within lidar_sensor_link
SENSOR_MASS = 0.001
SENSOR_INERTIA = (1e-5, 1e-5, 1e-5)
MIN_RANGE, MAX_RANGE = 0.1, 100.0
UPDATE_RATE = 50.0  # Hz


def fetch_mesh(cache: Path) -> Path:
    cache.mkdir(parents=True, exist_ok=True)
    dst = cache / "LW20.dae"
    if not dst.exists():
        print("downloading LW20.dae")
        urllib.request.urlretrieve(RAW, dst)
    return dst


def build(mesh_src: Path, out_dir: Path):
    out_dir.mkdir(parents=True, exist_ok=True)

    # ---- geometries.usdc: just the LW20 housing mesh ----
    geo_path = out_dir / "geometries.usdc"
    stage = Usd.Stage.CreateNew(str(geo_path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    root = UsdGeom.Scope.Define(stage, "/Geometries").GetPrim()
    stage.SetDefaultPrim(root)
    housing = UsdGeom.Xform.Define(stage, "/Geometries/lw20_housing").GetPrim()
    tris = collada_prototype(stage, housing, mesh_src)
    stage.GetRootLayer().Save()

    # ---- lidar_down.usda: additive layer on top of the base vehicle ----
    usda_path = out_dir / "lidar_down.usda"
    stage = Usd.Stage.CreateNew(str(usda_path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    stage.GetRootLayer().comment = (
        "X500 + downward LW20 rangefinder. Generated by sensors/lidar_down/build.py "
        "from PX4/PX4-gazebo-models (BSD-3-Clause). Edit the script, not this file."
    )

    root = UsdGeom.Xform.Define(stage, "/x500").GetPrim()
    root.GetReferences().AddReference("../../x500/x500.usda")
    stage.SetDefaultPrim(root)

    # Housing mesh: a sibling of /x500/body, visual-only (no separate rigid
    # body for the plastic case - its mass is folded into the sensor link
    # below, matching how little it is: see SENSOR_MASS).
    mesh_xyz, mesh_rpy = MESH_POSE
    mesh_prim = UsdGeom.Xform.Define(stage, "/x500/lidar_down_housing").GetPrim()
    mesh_prim.GetReferences().AddReference("./geometries.usdc", "/Geometries/lw20_housing")
    mesh_prim.SetInstanceable(True)
    set_pose(mesh_prim, mesh_xyz, rpy_quat(mesh_rpy))

    # Sensor rigid body: carries mass + the lidar sensor prim combined (the
    # SDF keeps them as separate link/sensor poses chained together; folded
    # into one prim here since both just describe where the single beam fires).
    sensor_xyz, sensor_rpy = SENSOR_LINK_POSE
    combined_rot = rpy_matrix(sensor_rpy) @ rpy_matrix(SENSOR_LOCAL_RPY)
    sensor = UsdGeom.Xform.Define(stage, "/x500/lidar_down").GetPrim()
    sensor.SetDocumentation(
        "Lightware LW20 single-beam rangefinder, aimed straight down (-Z in the body frame). "
        "PX4 consumes this as a MAVLink DISTANCE_SENSOR message - see sensors/README.md."
    )
    set_pose(sensor, sensor_xyz, matrix_to_quat(combined_rot))
    add_mass(sensor, SENSOR_MASS, SENSOR_INERTIA)
    # A near-zero collider: this body exists to carry the sensor frame and
    # its (negligible) mass, not to collide with anything.
    collision_cube = UsdGeom.Cube.Define(stage, "/x500/lidar_down/collision")
    collision_cube.CreateSizeAttr(0.001)
    collision_cube.CreateExtentAttr([(-0.5, -0.5, -0.5), (0.5, 0.5, 0.5)])
    add_collider(stage, collision_cube)

    add_generic_lidar(
        stage,
        "/x500/lidar_down/sensor",
        min_range=MIN_RANGE,
        max_range=MAX_RANGE,
        azimuth_deg=np.array([0.0]),
        elevation_deg=np.array([0.0]),
        scan_period_s=1.0 / UPDATE_RATE,
        horizontal_fov=0.0,
        vertical_fov=0.0,
        draw_points=True,
    )

    add_fixed_joint(
        stage,
        "/x500/joints/lidar_down_joint",
        body0="/x500/body",
        body1="/x500/lidar_down",
        pos0=sensor_xyz,
        rot0=Gf.Quatf(matrix_to_quat(combined_rot)),
    )

    stage.GetRootLayer().Save()
    print(f"LW20 housing: {tris} triangles")
    print("wrote", usda_path)


def main():
    mesh_src = fetch_mesh(REPO / ".cache" / "sensors" / "lw20")
    build(mesh_src, HERE)


if __name__ == "__main__":
    main()
