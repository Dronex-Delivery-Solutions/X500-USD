#!/usr/bin/env python3
"""Build the forward-facing RGB + depth camera accessory (Luxonis OAK-D
Lite) for the X500, from PX4/PX4-gazebo-models' x500_depth variant
(models/x500_depth, models/OakD-Lite - BSD-3-Clause).

Additive layer, same pattern as sensors/lidar_down and lidar_2d_front:
sensors/camera_depth/camera_depth.usda references ../../x500/x500.usda.

Needs only:  pip install usd-core pycollada numpy  (no Isaac Sim to build)

    python sensors/camera_depth/build.py

Authors two native UsdGeom.Camera prims (RGB + depth). The camera PRIM
itself is plain USD and not affected by the Isaac Sim 6 compatibility gap
described in sensors/README.md; what IS affected is capturing frames from
it at runtime - that needs isaacsim.sensors.experimental.rtx.RtxCamera +
CameraSensor (NOT Pegasus's own MonocularCamera graphical sensor class,
which imports the now-stubbed isaacsim.sensors.camera.camera.Camera).
Neither camera feeds PX4 directly in this variant (x500_vision does, via
synthetic vision-based odometry, which is a software problem, not an
asset one - see sensors/README.md); both are companion-computer sensors,
published over ROS 2 same as the real deployment architecture.
"""
from __future__ import annotations

import math
import sys
import urllib.request
from pathlib import Path

from pxr import Usd, UsdGeom

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent / "scripts"))
from _usd_common import add_camera, collada_prototype, set_pose  # noqa: E402

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
RAW = "https://raw.githubusercontent.com/PX4/PX4-gazebo-models/main/models/OakD-Lite/meshes/OakDLite.dae"

# ---- numbers from PX4-gazebo-models/models/x500_depth/model.sdf and
#      models/OakD-Lite/model.sdf. Every pose in that chain (camera_link
#      relative to base_link, each sensor relative to camera_link, the
#      mesh's own visual pose) is unrotated, so offsets just add and the
#      camera looks straight along body-forward (+X) - see
#      _usd_common.FORWARD_CAMERA_ROTATION for how that's realized in USD. ----
HOUSING_POSE_XYZ = (0.12, 0.03, 0.242)  # camera_link, relative to base_link
SENSOR_LOCAL_OFFSET = (0.01233, -0.03, 0.01878)  # both sensors share this offset within camera_link
SENSOR_XYZ = tuple(a + b for a, b in zip(HOUSING_POSE_XYZ, SENSOR_LOCAL_OFFSET))

# A conventional round aperture ("Super 35", common in Isaac Sim sample
# assets) - the SDF only gives horizontal_fov, not a physical sensor size,
# so this is a choice, not a measurement; it reproduces the documented FOV
# exactly regardless of which aperture is picked, since focal length is
# derived from it below.
APERTURE_MM = 20.955

CAMERAS = {
    # name, resolution (w, h), horizontal_fov (rad), clip (near, far), sensor model
    "rgb": ((1920, 1080), 1.204, (0.1, 100.0), "IMX214"),
    "depth": ((640, 480), 1.274, (0.2, 19.1), "StereoOV7251"),
}


def focal_length_mm(h_fov_rad: float, aperture_mm: float) -> float:
    return (aperture_mm / 2.0) / math.tan(h_fov_rad / 2.0)


def fetch_mesh(cache: Path) -> Path:
    cache.mkdir(parents=True, exist_ok=True)
    dst = cache / "OakDLite.dae"
    if not dst.exists():
        print("downloading OakDLite.dae")
        urllib.request.urlretrieve(RAW, dst)
    return dst


def build(mesh_src: Path, out_dir: Path):
    out_dir.mkdir(parents=True, exist_ok=True)

    geo_path = out_dir / "geometries.usdc"
    stage = Usd.Stage.CreateNew(str(geo_path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    root = UsdGeom.Scope.Define(stage, "/Geometries").GetPrim()
    stage.SetDefaultPrim(root)
    housing = UsdGeom.Xform.Define(stage, "/Geometries/oakd_housing").GetPrim()
    tris = collada_prototype(stage, housing, mesh_src)
    stage.GetRootLayer().Save()

    usda_path = out_dir / "camera_depth.usda"
    stage = Usd.Stage.CreateNew(str(usda_path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    stage.GetRootLayer().comment = (
        "X500 + forward-facing OAK-D Lite RGB/depth camera. Generated by "
        "sensors/camera_depth/build.py from PX4/PX4-gazebo-models (BSD-3-Clause). "
        "Edit the script, not this file."
    )

    root = UsdGeom.Xform.Define(stage, "/x500").GetPrim()
    root.GetReferences().AddReference("../../x500/x500.usda")
    stage.SetDefaultPrim(root)

    # Visual-only housing: no separate rigid body (61g, folded into /x500/body
    # the same way the base vehicle already does for e.g. the decals - see
    # sensors/README.md on why this is a reasonable simplification here but
    # not for the heavier lidar accessories).
    mesh_prim = UsdGeom.Xform.Define(stage, "/x500/camera_depth_housing").GetPrim()
    mesh_prim.GetReferences().AddReference("./geometries.usdc", "/Geometries/oakd_housing")
    mesh_prim.SetInstanceable(True)
    set_pose(mesh_prim, HOUSING_POSE_XYZ)

    cams = UsdGeom.Scope.Define(stage, "/x500/body/cameras").GetPrim()
    cams.SetDocumentation(
        "OAK-D Lite RGB + depth cameras, forward-facing. Not a separate rigid "
        "body (mounted rigidly on /x500/body, same frame) - capture them with "
        "isaacsim.sensors.experimental.rtx, not Pegasus's MonocularCamera; "
        "see sensors/README.md."
    )
    for name, (resolution, h_fov, clip, model) in CAMERAS.items():
        w, h = resolution
        focal = focal_length_mm(h_fov, APERTURE_MM) / 1000.0  # mm -> m (meter stage)
        add_camera(
            stage,
            f"/x500/body/cameras/{name}",
            SENSOR_XYZ,
            focal_length=focal,
            h_aperture=APERTURE_MM / 1000.0,
            v_aperture=APERTURE_MM / 1000.0 * h / w,
            clip_range=clip,
            tick_rate=30.0,  # matches the SDF's update_rate for both sensors
            model_name=model,
            model_vendor="Luxonis",
            market_name="OAK-D Lite",
        )

    stage.GetRootLayer().Save()
    print(f"OAK-D Lite housing: {tris} triangles")
    print("wrote", usda_path)


def main():
    mesh_src = fetch_mesh(REPO / ".cache" / "sensors" / "oakd")
    build(mesh_src, HERE)


if __name__ == "__main__":
    main()
