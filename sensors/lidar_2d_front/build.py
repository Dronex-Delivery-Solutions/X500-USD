#!/usr/bin/env python3
"""Build the forward-facing 270 deg planar lidar accessory for the X500,
from PX4/PX4-gazebo-models' x500_lidar_2d variant (models/x500_lidar_2d,
models/lidar_2d_v2 - BSD-3-Clause).

Additive layer: sensors/lidar_2d_front/lidar_2d_front.usda references
../../x500/x500.usda and adds one rigid body + fixed joint, same pattern
as sensors/lidar_down.

Needs only:  pip install usd-core pycollada numpy  (no Isaac Sim to build)

    python sensors/lidar_2d_front/build.py

Unlike the downward rangefinder, PX4 does not consume this one directly -
a 1080-beam planar scan has no MAVLink message PX4's SITL simulator
interface accepts (see sensors/README.md). This is a companion-computer
sensor even in simulation: wire it to ROS 2 (ROS2PublishLaserScan /
ROS2PublishPointCloud) and run obstacle avoidance there, same as the real
deployment architecture.
"""
from __future__ import annotations

import shutil
import sys
import urllib.request
from pathlib import Path

import numpy as np
from pxr import Gf, Usd, UsdGeom

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent / "scripts"))
from _usd_common import (  # noqa: E402
    add_collider,
    add_fixed_joint,
    add_generic_lidar,
    add_mass,
    collada_prototype,
    rpy_quat,
    set_pose,
)

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
RAW_DIR = "https://raw.githubusercontent.com/PX4/PX4-gazebo-models/main/models/lidar_2d_v2/meshes/"
MESH_FILES = ("lidar_2d_v2.dae", "lidar_2d_v2.jpg")

# ---- numbers from PX4-gazebo-models/models/x500_lidar_2d/model.sdf and
#      models/lidar_2d_v2/model.sdf ----
# The model's own include pose (relative to base_link) locates the link;
# the <joint> pose is the SDF attachment frame and is redundant with it
# (same ambiguity as x500_lidar_down - see sensors/lidar_down/build.py).
LINK_POSE_XYZ = (0.12, 0.0, 0.26)
SENSOR_LOCAL_Z_OFFSET = 0.055  # sensor pose within the link: "0 0 0.055 0 0 0"
LINK_MASS = 0.37
LINK_INERTIA = (0.00034437749999999994, 0.00034437749999999994, 0.00022199999999999998)
# name, local xyz (relative to link origin), box or cylinder, size
COLLIDERS = [
    ("base", (0, 0, 0.0205), "box", (0.06, 0.06, 0.041)),
    ("mid", (0, 0, 0.055), "cylinder", (0.025, 0.028)),  # radius, height
    ("top", (0, 0, 0.078), "box", (0.056, 0.056, 0.018)),
]
MIN_RANGE, MAX_RANGE = 0.1, 30.0
HALF_FOV_DEG = 135.0  # min_angle -2.356195 rad, max_angle +2.356195 rad
SAMPLES = 1080
UPDATE_RATE = 30.0  # Hz
MESH_UNIT_SCALE = 0.01  # lidar_2d_v2.dae declares <unit meter="0.01" name="centimeter">


def fetch_mesh(cache: Path) -> Path:
    cache.mkdir(parents=True, exist_ok=True)
    for name in MESH_FILES:
        dst = cache / name
        if not dst.exists():
            print(f"downloading {name}")
            urllib.request.urlretrieve(RAW_DIR + name, dst)
    return cache / "lidar_2d_v2.dae"


def build(mesh_src: Path, out_dir: Path):
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "textures").mkdir(exist_ok=True)
    shutil.copyfile(mesh_src.parent / "lidar_2d_v2.jpg", out_dir / "textures" / "lidar_2d_v2.jpg")

    geo_path = out_dir / "geometries.usdc"
    stage = Usd.Stage.CreateNew(str(geo_path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    root = UsdGeom.Scope.Define(stage, "/Geometries").GetPrim()
    stage.SetDefaultPrim(root)
    housing = UsdGeom.Xform.Define(stage, "/Geometries/lidar_housing").GetPrim()
    tris = collada_prototype(stage, housing, mesh_src, unit_scale=MESH_UNIT_SCALE)
    stage.GetRootLayer().Save()

    usda_path = out_dir / "lidar_2d_front.usda"
    stage = Usd.Stage.CreateNew(str(usda_path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    stage.GetRootLayer().comment = (
        "X500 + forward-facing 270deg planar lidar (lidar_2d_v2). Generated by "
        "sensors/lidar_2d_front/build.py from PX4/PX4-gazebo-models (BSD-3-Clause). "
        "Edit the script, not this file."
    )

    root = UsdGeom.Xform.Define(stage, "/x500").GetPrim()
    root.GetReferences().AddReference("../../x500/x500.usda")
    stage.SetDefaultPrim(root)

    body = UsdGeom.Xform.Define(stage, "/x500/lidar_2d_front").GetPrim()
    body.SetDocumentation(
        "Planar lidar (lidar_2d_v2 housing), 1080 beams over a 270deg arc centered "
        "on the body's forward (+X) axis. No PX4 MAVLink message carries this - "
        "publish it over ROS 2 instead, see sensors/README.md."
    )
    set_pose(body, LINK_POSE_XYZ)
    add_mass(body, LINK_MASS, LINK_INERTIA)

    mesh_prim = UsdGeom.Xform.Define(stage, "/x500/lidar_2d_front/visual").GetPrim()
    mesh_prim.GetReferences().AddReference("./geometries.usdc", "/Geometries/lidar_housing")
    mesh_prim.SetInstanceable(True)

    for name, xyz, shape, size in COLLIDERS:
        if shape == "box":
            cube = UsdGeom.Cube.Define(stage, f"/x500/lidar_2d_front/collisions/{name}")
            cube.CreateSizeAttr(1.0)
            cube.CreateExtentAttr([(-0.5, -0.5, -0.5), (0.5, 0.5, 0.5)])
            add_collider(stage, cube, xyz, Gf.Quatd(1, 0, 0, 0), size)
        else:
            radius, height = size
            cyl = UsdGeom.Cylinder.Define(stage, f"/x500/lidar_2d_front/collisions/{name}")
            cyl.CreateAxisAttr(UsdGeom.Tokens.z)
            cyl.CreateRadiusAttr(radius)
            cyl.CreateHeightAttr(height)
            cyl.CreateExtentAttr([(-radius, -radius, -height / 2), (radius, radius, height / 2)])
            add_collider(stage, cyl, xyz)

    azimuth = np.linspace(-HALF_FOV_DEG, HALF_FOV_DEG, SAMPLES)
    add_generic_lidar(
        stage,
        "/x500/lidar_2d_front/sensor",
        min_range=MIN_RANGE,
        max_range=MAX_RANGE,
        azimuth_deg=azimuth,
        elevation_deg=np.zeros(SAMPLES),
        scan_period_s=1.0 / UPDATE_RATE,
        horizontal_fov=2 * HALF_FOV_DEG,
        vertical_fov=0.0,
        draw_points=False,  # 1080 points/frame - too dense to draw by default
    )
    set_pose(stage.GetPrimAtPath("/x500/lidar_2d_front/sensor"), (0, 0, SENSOR_LOCAL_Z_OFFSET))

    add_fixed_joint(
        stage,
        "/x500/joints/lidar_2d_front_joint",
        body0="/x500/body",
        body1="/x500/lidar_2d_front",
        pos0=LINK_POSE_XYZ,
    )

    stage.GetRootLayer().Save()
    print(f"lidar_2d_v2 housing: {tris} triangles")
    print("wrote", usda_path)


def main():
    mesh_src = fetch_mesh(REPO / ".cache" / "sensors" / "lidar_2d_v2")
    build(mesh_src, HERE)


if __name__ == "__main__":
    main()
